const put = (bytes, at, value, width) => {
  for (let i = 0; i < width; i++) bytes[at + i] = Number((value >> BigInt(8 * i)) & 255n);
};
const rows = [];
for (const width of [16, 32, 64])
  for (const call of [false, true]) {
    const prefix = width === 16 ? '66' : width === 64 ? '48' : '';
    const body = prefix + (call ? 'ff1b' : 'ff2b');
    const target = 0x1000n + BigInt(body.length / 2 + (call ? 2 : 0));
    rows.push({
      name: `far-${call ? 'call-ret' : 'jump'}-${width}`,
      body,
      instructions: call ? 2 : 1,
      ...(call ? { suffix: prefix + 'cb' } : {}),
      width,
      call,
      target,
    });
  }
for (const call of [false, true])
  rows.push({
    name: `far-${call ? 'call-ret' : 'jump'}-immediate32`,
    body: call ? '9a091000000800' : 'ea071000000800',
    instructions: call ? 2 : 1,
    ...(call ? { suffix: 'cb' } : {}),
    width: 32,
    call,
    target: call ? 0x1009n : 0x1007n,
    legacy: true,
  });
rows.push({
  name: 'far-jump-64-a0-reset',
  body: 'c645059a48ff2b',
  instructions: 2,
  width: 64,
  call: false,
  target: 0x1007n,
  resetAccessed: true,
});
rows.push({
  ...rows.find((row) => row.width === 64 && row.call),
  name: 'far-call-ret-64-resume',
  resume: true,
});
const encode = (value) =>
  JSON.stringify(value, (_, v) => (typeof v === 'bigint' ? v.toString() : v));
export const farRows = rows.map((row) => ({
  ...row,
  requiresFar: true,
  ramBytes: 256,
  maxIterations: 10001,
  context(cpu) {
    const value = cpu.readContext();
    value.gdtr = { base: 0x4080n, limit: 15 };
    if (row.legacy) {
      value.mode = 'protected';
      value.segments.cs.default32 = true;
      value.segments.cs.long = false;
    }
    cpu.setContext(value);
    return value;
  },
  setup(s) {
    s.gpr[4] = 0x4060n;
    if (row.resetAccessed) s.gpr[5] = 0x4088n;
    put(s.ram, 16, row.target, row.width / 8);
    put(s.ram, 16 + row.width / 8, 8n, 2);
    s.ram.set([255, 255, 0, 0, 0, 0x9b, row.legacy ? 0xcf : 0xaf, 0], 136);
  },
  expected(s) {
    if (row.call) {
      const w = row.width / 8;
      put(s.ram, 96 - w, 8n, w);
      put(s.ram, 96 - 2 * w, 0x1000n + BigInt(row.body.length / 2), w);
    }
  },
  verify(cpu, expected) {
    if (encode(cpu.readContext()) !== encode(expected)) throw Error('stable far context changed');
  },
  resources(totals, n, sample, final, units) {
    const transfers = Number(n) * (row.call ? 2 : 1);
    if (row.resume) {
      if (totals.dispatches !== 0 || totals.nativeEntries !== Number(n) * 3)
        throw Error('far resume entry accounting');
    } else {
      if (totals.dispatches !== transfers)
        throw Error(`far dispatches ${totals.dispatches} != ${transfers}`);
      if (totals.nativeEntries !== transfers + 1)
        throw Error(`far entries ${totals.nativeEntries} != ${transfers + 1}`);
    }
    const compilations = sample === 0 ? (row.call ? 3 : 2) : 0;
    if (totals.cacheHits !== totals.nativeEntries - totals.compilations)
      throw Error('far exact cache hits');
    if (units.length !== (row.call ? 3 : 2) || final.cachedArtifacts !== units.length)
      throw Error('far cached unit count');
    if (final.cachedBytes !== units.reduce((size, unit) => size + unit.byteLength, 0))
      throw Error('far cached byte accounting');
    if (totals.generatedBytes !== (sample === 0 ? final.cachedBytes : 0))
      throw Error('far generated byte accounting');
    if (totals.compilations !== compilations)
      throw Error(`far compilations ${totals.compilations} != ${compilations}`);
  },
}));
