const parity = (value) => {
  let bits = Number(value & 255n),
    count = 0;
  while (bits) {
    count += bits & 1;
    bits >>>= 1;
  }
  return count % 2 === 0 ? 4n : 0n;
};
const controls = 0x3c7602n;
const encode = (value) =>
  JSON.stringify(value, (_, v) => (typeof v === 'bigint' ? v.toString() : v));
const add = (state, n) => {
  state.gpr[0] = n;
  state.flags = (state.flags & ~0x8d5n) | parity(n) | (n % 16n === 0n ? 16n : 0n);
};
const stableResources = (kind) => (totals, n, sample, final, units) => {
  const artifacts = kind === 'shadow' ? 2 : 1;
  const entries =
    kind === 'shadow' || kind === 'step' ? 2 * Number(n) : kind === 'stack' ? Number(n) + 1 : 1;
  if (totals.compilations !== (sample === 0 ? artifacts : 0))
    throw Error('system FLAGS compilation reuse');
  if (totals.nativeEntries !== entries || totals.cacheHits !== entries - totals.compilations)
    throw Error('system FLAGS native entry/cache accounting');
  if (totals.dispatches !== (kind === 'step' ? 0 : entries - 1))
    throw Error('system FLAGS dispatch accounting');
  if (units.length !== artifacts || final.cachedArtifacts !== artifacts)
    throw Error('system FLAGS retained profiles');
  const profiles = new Set(units.map((unit) => unit.boundaryObserved ?? false));
  if (
    kind === 'shadow'
      ? !profiles.has(false) || !profiles.has(true)
      : profiles.size !== 1 || !profiles.has(kind === 'step')
  )
    throw Error('system FLAGS profile identity');
  if (final.cachedBytes !== units.reduce((bytes, unit) => bytes + unit.byteLength, 0))
    throw Error('system FLAGS cache bytes');
  if (totals.generatedBytes !== (sample === 0 ? final.cachedBytes : 0))
    throw Error('system FLAGS generated bytes');
};

